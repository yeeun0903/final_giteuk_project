create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nickname text,
  photo_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.community_posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  content text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.community_posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  content text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.place_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null,
  place_name text not null,
  address text,
  menus jsonb not null default '[]'::jsonb,
  photo_count integer not null default 0,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.visits (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  place_id text not null,
  category text,
  place_name text,
  saving_amount integer not null default 0 check (saving_amount >= 0),
  visited_at timestamptz not null default now()
);

create table if not exists public.place_favorites (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  place_id text not null,
  place_name text,
  category text,
  created_at timestamptz not null default now(),
  unique (user_id, place_id)
);

create table if not exists public.community_likes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  post_id text not null,
  created_at timestamptz not null default now(),
  unique (user_id, post_id)
);

create table if not exists public.comment_likes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  comment_id text not null,
  created_at timestamptz not null default now(),
  unique (user_id, comment_id)
);

create table if not exists public.groupbuy_favorites (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id text not null,
  product_title text,
  created_at timestamptz not null default now(),
  unique (user_id, product_id)
);

create table if not exists public.groupbuy_events (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  product_id text,
  product_title text,
  event_type text not null check (event_type in ('favorite', 'unfavorite', 'participate', 'share')),
  created_at timestamptz not null default now()
);

create table if not exists public.auth_events (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  event_type text not null check (event_type in ('open_login', 'open_signup', 'login_complete', 'signup_complete')),
  entry_source text,
  return_page text,
  created_at timestamptz not null default now()
);

