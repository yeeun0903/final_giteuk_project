create or replace function public.get_my_saving_stats()
returns table (
  total_saving bigint,
  monthly_saving bigint,
  monthly_visit_count bigint
)
language sql
stable
as $$
  select
    coalesce(sum(saving_amount), 0)::bigint as total_saving,
    coalesce(
      sum(saving_amount) filter (
        where visited_at >= date_trunc('month', now())
          and visited_at < date_trunc('month', now()) + interval '1 month'
      ),
      0
    )::bigint as monthly_saving,
    count(*) filter (
      where visited_at >= date_trunc('month', now())
        and visited_at < date_trunc('month', now()) + interval '1 month'
    )::bigint as monthly_visit_count
  from public.visits
  where user_id = (select auth.uid());
$$;


